let currentLang: LanguageCode = 'en-US';

export function setLanguage(lang: LanguageCode): void {
  if (locales[lang]) currentLang = lang;
}

export function getLanguage(): LanguageCode {
  return currentLang;
}

export function t(key: keyof I18nStrings, params?: Record<string, string | number>): string {
  const locale = locales[currentLang] || locales['en-US'];
  let text = (locale as any)[key] ?? (locales['en-US'] as any)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getLocale(): I18nStrings {
  return locales[currentLang] || locales['en-US'];
}

export function detectSystemLanguage(): LanguageCode {
  const envLang = (process.env.LANG || process.env.LC_ALL || process.env.LC_MESSAGES || '').toLowerCase();
  if (envLang.startsWith('zh_tw') || envLang.startsWith('zh_hant')) return 'zh-TW';
  if (envLang.startsWith('zh')) return 'zh-CN';
  if (envLang.startsWith('ja')) return 'ja-JP';
  if (envLang.startsWith('ko')) return 'ko-KR';
  if (envLang.startsWith('es')) return 'es-ES';
  if (envLang.startsWith('pt')) return 'pt-BR';
  if (envLang.startsWith('ar')) return 'ar-SA';
  if (envLang.startsWith('fr')) return 'fr-FR';
  if (envLang.startsWith('de')) return 'de-DE';
  return 'en-US';
}
